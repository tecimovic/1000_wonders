#!/usr/bin/env python3
"""Turn a GraphQL introspection result into GraphQL SDL, with descriptions.

    python3 doc/entur/introspection-to-sdl.py introspection.json > journey-planner-v3.graphql

Types are sorted: Query first, then the rest alphabetically. Built-in
introspection types (__Schema etc.) are left out.
"""
import json
import sys


def type_ref(t):
    if t['kind'] == 'NON_NULL':
        return type_ref(t['ofType']) + '!'
    if t['kind'] == 'LIST':
        return '[' + type_ref(t['ofType']) + ']'
    return t['name']


def doc(text, indent=''):
    if not text:
        return ''
    text = text.strip().replace('"""', '\\"""')
    if '\n' not in text:
        return f'{indent}"""{text}"""\n'
    body = '\n'.join(indent + line if line else '' for line in text.split('\n'))
    return f'{indent}"""\n{body}\n{indent}"""\n'


def deprecated(item):
    if not item.get('isDeprecated'):
        return ''
    reason = item.get('deprecationReason')
    return f' @deprecated(reason: {json.dumps(reason)})' if reason else ' @deprecated'


def arg_list(args):
    if not args:
        return ''
    parts = []
    for a in args:
        default = f' = {a["defaultValue"]}' if a.get('defaultValue') is not None else ''
        line = f'{a["name"]}: {type_ref(a["type"])}{default}'
        if a.get('description'):
            line = f'"{" ".join(a["description"].split())}" ' + line
        parts.append(line)
    return '(\n' + ''.join(f'    {p}\n' for p in parts) + '  )'


def render(t):
    out = doc(t.get('description'))
    kind, name = t['kind'], t['name']
    if kind == 'SCALAR':
        return out + f'scalar {name}\n'
    if kind == 'UNION':
        return out + f'union {name} = ' + ' | '.join(p['name'] for p in t['possibleTypes']) + '\n'
    if kind == 'ENUM':
        values = ''.join(doc(v.get('description'), '  ') + f'  {v["name"]}{deprecated(v)}\n' for v in t['enumValues'])
        return out + f'enum {name} {{\n{values}}}\n'
    if kind == 'INPUT_OBJECT':
        fields = ''
        for f in t['inputFields']:
            default = f' = {f["defaultValue"]}' if f.get('defaultValue') is not None else ''
            fields += doc(f.get('description'), '  ') + f'  {f["name"]}: {type_ref(f["type"])}{default}\n'
        return out + f'input {name} {{\n{fields}}}\n'
    keyword = 'interface' if kind == 'INTERFACE' else 'type'
    implements = ''
    if t.get('interfaces'):
        implements = ' implements ' + ' & '.join(i['name'] for i in t['interfaces'])
    fields = ''
    for f in t['fields']:
        fields += doc(f.get('description'), '  ') + f'  {f["name"]}{arg_list(f["args"])}: {type_ref(f["type"])}{deprecated(f)}\n'
    return out + f'{keyword} {name}{implements} {{\n{fields}}}\n'


def main():
    schema = json.load(open(sys.argv[1]))['data']['__schema']
    query = schema['queryType']['name']
    types = [t for t in schema['types'] if not t['name'].startswith('__')]
    types.sort(key=lambda t: (t['name'] != query, t['name'].lower()))
    print('# Generated by doc/entur/introspection-to-sdl.py from a live introspection query.\n')
    print('\n'.join(render(t) for t in types))


main()
